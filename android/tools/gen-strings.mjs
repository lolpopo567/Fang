const kt = (s) => JSON.stringify(s).replace(/\$/g, '\\$');
const block = (lang) => {
  const all = { ...STRINGS[lang], ...ANDROID[lang] };
  return Object.entries(all).map(([k, v]) => `        ${kt(k)} to ${kt(v)},`).join('\n');
};
const out = `// Generated by tools/gen-strings.mjs from js/i18n.js. Do not edit by hand.
package app.fang.ui

internal val STRINGS: Map<String, Map<String, String>> = mapOf(
${Object.keys(STRINGS).map((lang) => `    ${kt(lang)} to mapOf(\n${block(lang)}\n    ),`).join('\n')}
)
`;
fs.writeFileSync(new URL('../app/src/main/java/app/fang/ui/Strings.kt', import.meta.url), out);

// Writes app/src/main/java/app/fang/ui/IconPaths.kt from the web app's css/icons.css (Lucide line icons,
// ISC licence), so both apps draw the same icons. Run from android/: node tools/gen-icons.mjs
import fs from 'node:fs';

const css = fs.readFileSync(new URL('../../css/icons.css', import.meta.url), 'utf8');
const attrs = (s) => Object.fromEntries([...s.matchAll(/([\w-]+)='([^']*)'/g)].map((m) => [m[1], m[2]]));
const n = (v) => Number(v ?? 0);

// Compose's path parser takes SVG path data, so rects and circles become paths.
function toPath(tag, a) {
  if (tag === 'path') return a.d;
  if (tag === 'circle') {
    const [cx, cy, r] = [n(a.cx), n(a.cy), n(a.r)];
    return `M${cx - r} ${cy}a${r} ${r} 0 1 0 ${2 * r} 0a${r} ${r} 0 1 0 ${-2 * r} 0z`;
  }
  if (tag === 'rect') {
    const [x, y, w, h, r] = [n(a.x), n(a.y), n(a.width), n(a.height), n(a.rx)];
    return `M${x + r} ${y}H${x + w - r}a${r} ${r} 0 0 1 ${r} ${r}V${y + h - r}a${r} ${r} 0 0 1 ${-r} ${r}H${x + r}a${r} ${r} 0 0 1 ${-r} ${-r}V${y + r}a${r} ${r} 0 0 1 ${r} ${-r}z`;
  }
  throw new Error(`unsupported <${tag}>`);
}

const icons = [];
for (const [, name, uri] of css.matchAll(/--i-([a-z-]+): url\("data:image\/svg\+xml,([^"]+)"\)/g)) {
  const svg = decodeURIComponent(uri);
  const parts = [...svg.matchAll(/<(\w+) ([^>]*)\/>/g)].map(([, tag, a]) => {
    const at = attrs(a);
    return { d: toPath(tag, at), filled: at.fill === 'black' };
  });
  icons.push({ name, parts });
}

const camel = (s) => s.replace(/-(\w)/g, (_, c) => c.toUpperCase());
const out = `// Generated by tools/gen-icons.mjs from css/icons.css (Lucide, ISC licence). Do not edit by hand.
package app.fang.ui

internal val ICON_PATHS: Map<String, List<Pair<String, Boolean>>> = mapOf(
${icons.map(({ name, parts }) => `    "${camel(name)}" to listOf(${parts.map((p) => `"${p.d}" to ${p.filled}`).join(', ')}),`).join('\n')}
)
`;
fs.writeFileSync(new URL('../app/src/main/java/app/fang/ui/IconPaths.kt', import.meta.url), out);
console.log('wrote IconPaths.kt:', icons.map((i) => i.name).join(' '));
